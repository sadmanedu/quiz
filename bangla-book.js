  function meaningfulQuestions(chapterInfo) {
    const specialFactories = {
      "vowel-pair": () => vowelPairPractice(chapterInfo),
      vowels: allVowelPractice,
      kar: () => karPractice(chapterInfo),
      "consonant-group": () => groupLetterPractice(chapterInfo),
      "special-letters": () => specialLetterPractice(chapterInfo),
      "special-signs": specialSignPractice,
      consonants: consonantPractice
    };
    if (specialFactories[chapterInfo.type]) return specialFactories[chapterInfo.type]();
    const conceptQuestions = extraQuestions(chapterInfo.type, chapterInfo);
    const words = vocabularyByType[chapterInfo.type] || vocabularyByType.words;
    const theme = vocabularyThemes[chapterInfo.type] || vocabularyThemes.words;
    const wordQuestions = vocabularyQuestions(words, theme);
    return [...conceptQuestions, ...wordQuestions].slice(0, 20);
  }

  function makeChapterQuestions(chapterInfo) {
    // Every item tests a lesson concept, vocabulary word, reading skill, or language pattern.
    // We intentionally avoid chapter-title, serial-number, and generic study-habit filler questions.
    return meaningfulQuestions(chapterInfo).slice(0, 20);
  }

  function getChapter(id) {
    return chapters.find((item) => item.id === id);
  }

  function makeChapterQuiz(id) {
    const chapterInfo = getChapter(id);
    if (!chapterInfo) return null;
    return {
      id: chapterInfo.id,
      title: `পাঠ ${bn(chapterInfo.lesson)}: ${chapterInfo.title}`,
      description: "২০টি প্রশ্ন • প্রতিটি উত্তরের সঙ্গে সহজ ব্যাখ্যা",
      chapter: chapterInfo,
      questions: makeChapterQuestions(chapterInfo)
    };
  }

  function shuffle(items) {
    const shuffled = [...items];
    for (let index = shuffled.length - 1; index > 0; index -= 1) {
      const swapIndex = Math.floor(Math.random() * (index + 1));
      [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
    }
    return shuffled;
  }

  function makeFullBookQuiz(excludedQuestionIds = []) {
    const excluded = new Set(excludedQuestionIds);
    const fullQuestionPool = chapters.flatMap((chapterInfo) =>
      makeChapterQuestions(chapterInfo).map((item, questionIndex) => ({
        ...item,
        id: `${chapterInfo.id}-question-${questionIndex + 1}`,
        sourceChapter: chapterInfo.title
      }))
    );
    const availableQuestions = fullQuestionPool.filter((item) => !excluded.has(item.id));
    const pool = availableQuestions.length >= 10 ? availableQuestions : fullQuestionPool;
    const selectedQuestions = shuffle(pool).slice(0, 10);

    return {
      id: "bangla-full-book",
      title: "সম্পূর্ণ বই: র‌্যান্ডম কুইজ",
      description: "বইয়ের সব পাঠ থেকে এলোমেলো ১০টি নতুন প্রশ্ন",
      availableQuestionCount: availableQuestions.length,
      questionIds: selectedQuestions.map((item) => item.id),
      questions: selectedQuestions
    };
  }

  return { chapters, groups, getChapter, makeChapterQuestions, makeChapterQuiz, makeFullBookQuiz };
