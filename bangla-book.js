  function hash(text) {
    let value = 0;
    for (let index = 0; index < text.length; index += 1) value = (value * 31 + text.charCodeAt(index)) | 0;
    return Math.abs(value);
  }

  function question(prompt, correct, wrong, explanation, visual = "অ") {
    const choices = [...new Set(wrong.filter((item) => item !== correct))].slice(0, 3);
    while (choices.length < 3) choices.push("আরেকটি উত্তর");
    const answer = hash(prompt) % 4;
    choices.splice(answer, 0, correct);
    return { prompt, options: choices, answer, explanation, visual };
  }

